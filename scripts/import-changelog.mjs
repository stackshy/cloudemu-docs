#!/usr/bin/env node
/**
 * import-changelog — pull cloudemu's official GitHub Releases and generate the
 * data the Release Ledger renders (lib/changelog.generated.ts).
 *
 * The product (github.com/stackshy/cloudemu) publishes hand-written release
 * notes per tag; this is the source of truth for the docs changelog. Release
 * bodies are parsed into structured blocks (headings / bullets / paragraphs)
 * so arbitrary note text renders safely as React — no raw HTML/MDX.
 *
 * Usage:  node scripts/import-changelog.mjs [--repo owner/name]
 * Run it after a new product release; commit the regenerated file.
 */
import { writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';

const repoArg = process.argv.indexOf('--repo');
const REPO = repoArg >= 0 ? process.argv[repoArg + 1] : 'stackshy/cloudemu';

const raw = execSync(`gh api 'repos/${REPO}/releases?per_page=100'`, { maxBuffer: 32 * 1024 * 1024 }).toString();
const releases = JSON.parse(raw).filter((r) => !r.draft && !r.prerelease);

const EMOJI = /[\u{1F000}-\u{1FAFF}\u{2190}-\u{21FF}\u{2300}-\u{27BF}\u{2B00}-\u{2BFF}\u{FE0F}\u{200D}]/gu;

function cleanTitle(name, tag) {
  if (!name) return '';
  let t = name.replace(EMOJI, '').trim();
  // drop a leading version token, then a dash/em-dash separator
  t = t.replace(new RegExp(`^${tag}\\b`), '').replace(/^v?\d+\.\d+\.\d+\b/, '').trim();
  t = t.replace(/^[—\-:·]+\s*/, '').trim();
  return t;
}

// Strip known HTML tags (b, summary, code, …) but leave placeholder text like
// <cluster-uid> intact.
const stripTags = (s) =>
  s.replace(
    /<\/?(details|summary|b|strong|i|em|p|div|a|img|picture|source|br|code|pre|h[1-6]|ul|ol|li|table|thead|tbody|tr|td|th|span)(\s[^>]*)?>/gi,
    '',
  );

/** Parse a release body into safe structured blocks (handles <details>). */
function parseBody(body) {
  const src = (body || '').replace(/\r\n/g, '\n');
  const lines = src.split('\n');
  const root = [];
  let det = null; // current <details> block, or null
  let awaitingSummary = false;
  let para = [];
  const target = () => (det ? det.children : root);
  const flush = () => {
    if (para.length) {
      const text = para.join(' ').trim();
      if (text) target().push({ t: 'p', text });
      para = [];
    }
  };

  for (let line of lines) {
    line = line.replace(EMOJI, '');

    if (/<details[\s>]/i.test(line)) {
      flush();
      det = { t: 'details', summary: '', children: [] };
      const sm = line.match(/<summary>([\s\S]*?)<\/summary>/i);
      if (sm) det.summary = stripTags(sm[1]).trim();
      else awaitingSummary = true;
      continue;
    }
    if (awaitingSummary) {
      const sm = line.match(/<summary>([\s\S]*?)<\/summary>/i);
      if (sm && det) {
        det.summary = stripTags(sm[1]).trim();
        awaitingSummary = false;
      }
      continue;
    }
    if (/<\/details>/i.test(line)) {
      flush();
      if (det) {
        if (det.children.length || det.summary) root.push(det);
        det = null;
      }
      continue;
    }

    // drop HTML-only / logo header lines
    if (/^\s*<\/?(p|picture|source|img|div|a)[\s>]/i.test(line)) continue;
    line = stripTags(line);
    const trimmed = line.trim();
    if (!trimmed) { flush(); continue; }
    if (/^\|/.test(trimmed)) continue; // skip table rows
    if (/^\*{0,2}(full changelog)/i.test(trimmed)) continue;

    const h = trimmed.match(/^(#{1,4})\s+(.*)$/);
    if (h) {
      flush();
      const text = h[2].replace(/[:•]+\s*$/, '').trim();
      if (/^(release notes\b|v?\d+\.\d+\.\d+\b|what.s new\b|highlights?\b)/i.test(text) && text.length < 42) continue;
      if (text) target().push({ t: 'h', level: Math.min(Math.max(h[1].length, 2), 4), text });
      continue;
    }
    const li = trimmed.match(/^(?:\d+\.|[-*])\s+(.*)$/);
    if (li) { flush(); target().push({ t: 'li', text: li[1].trim() }); continue; }

    para.push(trimmed);
  }
  flush();
  if (det && (det.children.length || det.summary)) root.push(det);
  return root.slice(0, 80);
}

const out = releases.map((r) => ({
  version: r.tag_name.replace(/^v/, ''),
  tag: r.tag_name,
  title: cleanTitle(r.name, r.tag_name),
  date: (r.published_at || r.created_at || '').slice(0, 10),
  url: r.html_url,
  blocks: parseBody(r.body),
}));

const header = `// GENERATED by scripts/import-changelog.mjs — do not edit by hand.
// Source: github.com/${REPO} Releases. Re-run the script after a new release.

export type ChangelogBlock =
  | { t: 'h'; level: number; text: string }
  | { t: 'li'; text: string }
  | { t: 'p'; text: string }
  | { t: 'details'; summary: string; children: ChangelogBlock[] };

export interface ChangelogRelease {
  version: string;
  tag: string;
  title: string;
  date: string;
  url: string;
  blocks: ChangelogBlock[];
}

export const RELEASES: ChangelogRelease[] = `;

writeFileSync('lib/changelog.generated.ts', header + JSON.stringify(out, null, 2) + ';\n');
console.log(`Imported ${out.length} releases from ${REPO} → lib/changelog.generated.ts`);
